"""Labelled Polish sanity check from the PolEval 2025 Śmigiel shared task.

Our articles have no known machine-written texts, so the detectors' recall
cannot be measured on them. Śmigiel has both kinds (literature, reviews, social
media, Wikipedia; generated by Bielik, PLLuM, Llama, Mistral and Gemma), so a
balanced sample of its training set checks that our implementation separates
them about as well as reported at PolEval (about 0.80 accuracy for Binoculars).

The texts are research-only and are kept out of git (``data/external/``).
"""

import csv
import math
import random
from collections.abc import Sequence
from pathlib import Path

import pandas as pd
import requests

from news_detector.detect.data import PROJECT_ROOT, DetectError, text_key
from news_detector.detect.report import DIRECTIONS, threshold_at_fpr
from news_detector.utils.logger import get_logger

logger = get_logger(__name__)

SMIGIEL_URL = "https://raw.githubusercontent.com/poleval/2025-smigiel/main/data/train"
SMIGIEL_DIR = PROJECT_ROOT / "data" / "external" / "smigiel"
SAMPLE_CSV = SMIGIEL_DIR / "sample.csv"


def _download(name: str) -> Path:
    path = SMIGIEL_DIR / name
    if path.exists():
        return path
    SMIGIEL_DIR.mkdir(parents=True, exist_ok=True)
    logger.info("Downloading %s/%s", SMIGIEL_URL, name)
    try:
        response = requests.get(f"{SMIGIEL_URL}/{name}", timeout=120)
        response.raise_for_status()
    except requests.RequestException as exc:
        raise DetectError(f"Cannot download Śmigiel {name}: {exc}") from exc
    path.write_bytes(response.content)
    return path


def prepare_sample(size: int = 1000, seed: int = 42, output: Path = SAMPLE_CSV) -> Path:
    """Write a class-balanced sample of the Śmigiel training set.

    Args:
        size: Number of texts; half human-written (0), half generated (1).
        seed: Random seed of the sample.
        output: CSV with ``text`` and ``label`` columns.

    Returns:
        The path of the written CSV.
    """
    texts = _download("data.tsv").read_text(encoding="utf-8").splitlines()
    labels = _download("labels.tsv").read_text(encoding="utf-8").splitlines()
    if len(texts) != len(labels):
        raise DetectError(f"Śmigiel has {len(texts)} texts but {len(labels)} labels")

    by_label: dict[str, list[str]] = {"0": [], "1": []}
    for text, label in zip(texts, labels, strict=True):
        if text.strip() and label.strip() in by_label:
            by_label[label.strip()].append(text)
    rng = random.Random(seed)
    rows = [
        {"text": text, "label": label}
        for label, pool in by_label.items()
        for text in rng.sample(pool, min(size // 2, len(pool)))
    ]
    rng.shuffle(rows)

    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=("text", "label"))
        writer.writeheader()
        writer.writerows(rows)
    return output


def _auc(machine_score: pd.Series, labels: pd.Series) -> float:
    """Probability that a random generated text scores above a human one."""
    ranks = machine_score.rank()
    positives = int(labels.sum())
    negatives = len(labels) - positives
    if not positives or not negatives:
        return math.nan
    rank_sum = float(ranks[labels == 1].sum())
    return (rank_sum - positives * (positives + 1) / 2) / (positives * negatives)


def evaluate(
    scores_path: Path,
    sample_path: Path = SAMPLE_CSV,
    fprs: Sequence[float] = (0.01, 0.05),
) -> pd.DataFrame:
    """AUC, accuracy and recall at fixed false positive rates on the sample.

    The accuracy uses the median score as the threshold, as the winning
    PolEval system did; the classes are balanced, so this is a fair default.
    """
    sample = pd.read_csv(sample_path)
    sample["text_key"] = sample["text"].map(text_key)
    data = sample.drop(columns="text").merge(
        pd.read_csv(scores_path), on="text_key", how="inner"
    )
    if data.empty:
        raise DetectError(f"No text of {sample_path} has a score in {scores_path}")
    labels = data["label"].astype(int)

    rows: list[dict[str, object]] = []
    for detector, direction in DIRECTIONS.items():
        if detector not in data.columns:
            continue
        machine_score = direction * data[detector]
        median = float(machine_score.median())
        row: dict[str, object] = {
            "detector": detector,
            "n": len(data),
            "auc": _auc(machine_score, labels),
            "accuracy_median": float(((machine_score > median) == labels).mean()),
        }
        for fpr in fprs:
            threshold = threshold_at_fpr(machine_score[labels == 0], fpr)
            row[f"recall_at_fpr_{fpr:g}"] = float(
                (machine_score[labels == 1] > threshold).mean()
            )
        rows.append(row)
    return pd.DataFrame(rows)
